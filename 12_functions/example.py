# ЗАДАЧА:
# Нужна функция, которая считает итоговую цену покупки с учётом скидки.
# По умолчанию скидки нет (0%), но можно указать любую скидку в процентах.
# Проверить функцию на нескольких покупках и напечатать результаты.

# ПЛАН РЕШЕНИЯ:
# 1. Создать функцию calculate_price(price, discount=0), которая
#    возвращает цену со скидкой через return
# 2. Вызвать функцию несколько раз с разными аргументами
# 3. Напечатать результаты каждого вызова


def calculate_price(price, discount=0):     # discount по умолчанию 0 (нет скидки)
    discount_amount = price * discount / 100  # сколько денег вычесть
    final_price = price - discount_amount     # итоговая цена
    return final_price                         # возвращаем результат вызывающему коду


# шаг 2: вызываем функцию с разными аргументами
price_1 = calculate_price(1000)          # без скидки, discount = 0 по умолчанию
price_2 = calculate_price(1000, 10)      # скидка 10%
price_3 = calculate_price(2500, 25)      # скидка 25%

# шаг 3: печатаем результаты
print(f"Цена без скидки: {price_1} руб.")
print(f"Цена со скидкой 10%: {price_2} руб.")
print(f"Цена со скидкой 25%: {price_3} руб.")
