# ЗАДАЧА:
# Простой пример игры "Угадай число", которая объединяет random, while,
# input() и условия — чтобы показать, как разные темы работают вместе
# в одной программе. Это НЕ финальный проект, а просто пример-разминка
# перед ним.

# ПЛАН РЕШЕНИЯ:
# 1. Подключить модуль random и загадать число от 1 до 20
# 2. Завести переменную для счёта попыток
# 3. В цикле while спрашивать у игрока число, пока он не угадает
# 4. После каждой попытки подсказывать "больше" или "меньше"
# 5. Когда угадано — поздравить и сказать, за сколько попыток угадали

import random

загаданное_число = random.randint(1, 20)  # шаг 1: компьютер загадывает число
попытки = 0                                # шаг 2: считаем количество попыток
угадал = False

print("Добро пожаловать в игру 'Угадай число'!")
print("Я загадал число от 1 до 20. Попробуй угадать!")

while not угадал:                          # шаг 3: повторяем, пока не угадано
    ввод = input("Введи число: ")

    try:
        число_игрока = int(ввод)
    except ValueError:
        print("Пожалуйста, вводи именно число.")
        continue

    попытки += 1

    if число_игрока == загаданное_число:    # шаг 5: игрок угадал
        угадал = True
        print("Поздравляю! Ты угадал число за", попытки, "попыток(-ки)!")
    elif число_игрока < загаданное_число:    # шаг 4: подсказка
        print("Загаданное число больше.")
    else:
        print("Загаданное число меньше.")

print("Спасибо за игру!")
