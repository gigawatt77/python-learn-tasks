"""
Готовое решение финального проекта: текстовая викторина.

Можно проверить, "проиграв" в неё через передачу ответов в stdin, например:
printf "4\nмосква\n7\n" | python3 solutions/task_01_project.py
"""

вопросы = [
    {"вопрос": "Сколько будет 2 + 2?", "ответ": "4"},
    {"вопрос": "Столица России?", "ответ": "москва"},
    {"вопрос": "Сколько дней в неделе?", "ответ": "7"},
]


def задать_вопрос(вопрос_словарь):
    """Печатает вопрос, спрашивает ответ и возвращает True/False."""
    print(вопрос_словарь["вопрос"])
    ответ_игрока = input("Твой ответ: ")

    правильный_ответ = вопрос_словарь["ответ"].strip().lower()
    ответ_игрока = ответ_игрока.strip().lower()

    if ответ_игрока == правильный_ответ:
        print("Верно!")
        return True
    else:
        print("Неверно. Правильный ответ:", вопрос_словарь["ответ"])
        return False


def показать_результат(правильных, всего):
    """Печатает итоговый результат викторины."""
    print("Ты ответил правильно на", правильных, "из", всего, "вопросов!")


def главная():
    """Основная функция, которая запускает викторину."""
    print("Добро пожаловать в викторину!")
    правильных = 0

    for вопрос_словарь in вопросы:
        если_верно = задать_вопрос(вопрос_словарь)
        if если_верно:
            правильных += 1

    показать_результат(правильных, len(вопросы))
    print("Спасибо за игру!")


if __name__ == "__main__":
    главная()
