# ЗАДАЧА:
# Записать в текстовый файл короткое сообщение, а затем прочитать его
# обратно и напечатать на экране. Файл должен создаваться рядом с этим
# скриптом, независимо от того, из какой папки его запускают.

# ПЛАН РЕШЕНИЯ:
# 1. Подключить модуль os, чтобы построить надёжный путь к файлу
# 2. Собрать полный путь к файлу example_data.txt рядом со скриптом
# 3. Открыть файл на запись и записать в него текст
# 4. Открыть тот же файл на чтение и прочитать текст
# 5. Напечатать прочитанный текст на экране

import os

путь_к_файлу = os.path.join(os.path.dirname(__file__), "example_data.txt")  # шаг 2

with open(путь_к_файлу, "w", encoding="utf-8") as файл:   # шаг 3: пишем в файл
    файл.write("Привет из файла!\n")
    файл.write("Это вторая строка.")

with open(путь_к_файлу, "r", encoding="utf-8") as файл:   # шаг 4: читаем файл
    содержимое = файл.read()

print("Содержимое файла:")   # шаг 5
print(содержимое)
