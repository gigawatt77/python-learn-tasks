# ЗАДАЧА:
# Посчитать, сколько шоколадок можно раздать поровну между друзьями, а
# сколько останется лишних, а также посчитать общую стоимость покупки
# с учётом приоритета операций.

# ПЛАН РЕШЕНИЯ:
# 1. Разделить шоколадки между друзьями с помощью // и % (целая часть и остаток)
# 2. Посчитать стоимость покупки, используя правильный приоритет операций
# 3. Напечатать все результаты

chocolates = 23     # всего шоколадок
friends = 5          # количество друзей

each_gets = chocolates // friends   # целая часть -- сколько получит каждый
leftover = chocolates % friends     # остаток -- сколько останется лишних

print("Каждому достанется:", each_gets)
print("Останется лишних:", leftover)

# Стоимость покупки: 3 шоколадки по 50 рублей + доставка 100 рублей
price_per_item = 50
items = 3
delivery = 100

# Умножение выполнится раньше сложения благодаря приоритету операций
total_price = price_per_item * items + delivery
print("Итоговая стоимость:", total_price)   # 50*3 + 100 = 250

# А степень нужна, например, чтобы посчитать площадь квадратного стола
