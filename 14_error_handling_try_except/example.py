# ЗАДАЧА:
# Есть список данных, введённых "пользователем" (заранее заданный, без
# input()), среди которых попадаются некорректные значения. Нужно для
# каждого значения посчитать 100, делённое на это число, и обработать
# ошибки, если значение не число или равно нулю.

# ПЛАН РЕШЕНИЯ:
# 1. Взять список значений (среди них есть "плохие" данные)
# 2. Для каждого значения попробовать превратить его в число и поделить 100 на него
# 3. Если значение не превращается в число — поймать ValueError
# 4. Если значение равно нулю — поймать ZeroDivisionError
# 5. Напечатать результат или сообщение об ошибке

данные = ["10", "0", "abc", "5"]

for значение in данные:
    print("Обрабатываем значение:", значение)
    try:
        число = int(значение)          # шаг 2: пробуем превратить в число
        результат = 100 / число        # и поделить 100 на него
        print("Результат:", результат)
    except ValueError:
        print("Ошибка: это не похоже на число!")
    except ZeroDivisionError:
        print("Ошибка: на ноль делить нельзя!")

print("Обработка данных завершена.")
