# ЗАДАЧА:
# Сделать мини-игру "Угадай число": компьютер загадывает число от 1 до 10,
# а у нас есть список из нескольких "попыток игрока" (без input(), просто
# заранее заданные числа). Нужно проверить каждую попытку и сказать,
# угадал игрок или нет.

# ПЛАН РЕШЕНИЯ:
# 1. Подключить модуль random
# 2. Зафиксировать seed, чтобы результат всегда был одинаковым
# 3. Загадать число от 1 до 10
# 4. Взять список готовых "попыток" игрока
# 5. Для каждой попытки сравнить её с загаданным числом и напечатать результат

import random

random.seed(42)  # фиксируем seed, чтобы игра была предсказуемой

загаданное_число = random.randint(1, 10)  # шаг 3: компьютер "загадывает" число
print("Компьютер загадал число от 1 до 10...")

попытки = [3, 7, 1, 5]  # шаг 4: заранее заданные попытки игрока

for попытка in попытки:
    print("Игрок пробует число:", попытка)
    if попытка == загаданное_число:
        print("Правильно! Ты угадал число!")
    elif попытка < загаданное_число:
        print("Мимо! Загаданное число больше.")
    else:
        print("Мимо! Загаданное число меньше.")

print("Загаданное число было:", загаданное_число)
