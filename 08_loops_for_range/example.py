# ЗАДАЧА:
# Напечатать таблицу умножения числа 5 (от 1 до 5), а также пройти по
# списку любимых предметов ученика и напечатать каждый предмет с номером.

# ПЛАН РЕШЕНИЯ:
# 1. Циклом for с range() напечатать строки таблицы умножения на 5
# 2. Завести список предметов
# 3. Циклом for по списку напечатать каждый предмет с его номером

chislo = 5

for i in range(1, 6):                     # i пробегает значения 1, 2, 3, 4, 5
    print(chislo, "x", i, "=", chislo * i)  # печатаем строку умножения

print("---")                               # разделитель между частями примера

predmety = ["математика", "информатика", "физкультура"]

for indeks, predmet in enumerate(predmety, start=1):  # start=1: нумерация с 1
    print(indeks, predmet)                             # печатаем номер и предмет
