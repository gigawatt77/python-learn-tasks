# скорость (дробное число) и флаг "герой ли он" (True/False),
# а затем красиво напечатать всю информацию о персонаже.

# ПЛАН РЕШЕНИЯ:
# 1. Создать переменные разных типов: str, int, float, bool
# 2. Проверить тип каждой переменной с помощью type()
# 3. Напечатать анкету персонажа

character_name = "Огнегрив"     # str  — имя персонажа
level = 7                        # int  — целое число: уровень персонажа
speed = 5.5                      # float — дробное число: скорость передвижения
is_hero = True                   # bool — герой это или злодей

# Посмотрим, какого типа получились наши переменные
print(type(character_name))      # <class 'str'>
print(type(level))               # <class 'int'>
print(type(speed))               # <class 'float'>
print(type(is_hero))             # <class 'bool'>

print("==========")
print("АНКЕТА ПЕРСОНАЖА")
print("==========")
print("Имя:", character_name)    # print с запятой печатает несколько значений через пробел
print("Уровень:", level)
print("Скорость:", speed)
print("Герой:", is_hero)
