# ЗАДАЧА:
# Дано полное имя ученика одной строкой в верхнем регистре с лишними
# пробелами. Нужно привести имя к аккуратному виду, разбить на имя и
# фамилию, найти нужную часть текста и красиво напечатать результат
# с помощью f-строки.

# ПЛАН РЕШЕНИЯ:
# 1. Убрать лишние пробелы и перевести текст в обычный регистр
# 2. Разбить строку на имя и фамилию с помощью split()
# 3. Найти индекс, где начинается фамилия, и напечатать всё через f-строку

raw_name = "  анна   СМИРНОВА  "          # шаг 0: исходные "грязные" данные

clean_name = raw_name.strip()             # шаг 1: убираем пробелы по краям
clean_name = clean_name.title()           # делаем первые буквы заглавными
print("Очищенное имя:", clean_name)       # Анна   Смирнова (пробелы внутри остались)

parts = clean_name.split()                # шаг 2: split() без аргумента убирает
                                           # и лишние пробелы внутри строки
first_name = parts[0]                     # первый элемент списка — имя
last_name = parts[1]                      # второй элемент списка — фамилия

position = clean_name.find(last_name)     # шаг 3: индекс, где начинается фамилия
print(f"Фамилия '{last_name}' начинается с индекса {position}")

print(f"Имя: {first_name}, Фамилия: {last_name}")
print(f"Длина полного имени без пробелов: {len(first_name + last_name)} символов")
