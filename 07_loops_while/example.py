# ЗАДАЧА:
# Смоделировать обратный отсчёт перед стартом ракеты: от 5 до 1, а после
# него напечатать "Старт!". Также посчитать сумму чисел от 1 до 5,
# используя отдельный цикл while.

# ПЛАН РЕШЕНИЯ:
# 1. Завести счётчик, равный 5, и уменьшать его в цикле while, пока он больше 0
# 2. После цикла напечатать "Старт!"
# 3. Отдельным циклом while посчитать сумму чисел от 1 до 5

schet = 5

while schet > 0:               # пока счётчик больше нуля — продолжаем отсчёт
    print(schet)                # печатаем текущее число
    schet = schet - 1           # уменьшаем счётчик на 1

print("Старт!")                 # цикл закончился — ракета летит

# теперь посчитаем сумму чисел от 1 до 5 с помощью while
chislo = 1
summa = 0

while chislo <= 5:
    summa = summa + chislo      # прибавляем текущее число к сумме
    chislo = chislo + 1         # переходим к следующему числу

print("Сумма чисел от 1 до 5:", summa)
