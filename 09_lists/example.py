# ЗАДАЧА:
# Есть список любимых игр. Нужно напечатать первую и последнюю игру,
# добавить новую игру в конец списка, убрать одну ненужную игру,
# а затем напечатать весь список по одному элементу на строку с номером.

# ПЛАН РЕШЕНИЯ:
# 1. Создать список с играми
# 2. Напечатать первую и последнюю игру (индексы 0 и -1)
# 3. Добавить новую игру и убрать ненужную (append и remove)
# 4. Перебрать список циклом for и напечатать каждую игру с номером

games = ["Minecraft", "Roblox", "Among Us", "Tetris"]  # шаг 1: список игр

print("Первая игра:", games[0])     # шаг 2: индекс 0 — первый элемент
print("Последняя игра:", games[-1])  # отрицательный индекс -1 — последний элемент

games.append("Terraria")   # шаг 3: добавили новую игру в конец
games.remove("Tetris")     # убрали Tetris из списка

print("Всего игр:", len(games))  # len() считает количество элементов

print("Список игр:")
for i, game in enumerate(games):   # шаг 4: перебираем список с номером
    print(i + 1, "-", game)        # +1, чтобы нумерация была с 1, а не с 0
