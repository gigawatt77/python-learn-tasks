# ЗАДАЧА:
# Спросить у пользователя имя и возраст, а затем напечатать, сколько лет
# ему будет через 5 лет.
#
# ВНИМАНИЕ: этот файл читает данные из ввода (input), поэтому при запуске
# в него нужно передать две строки через стандартный ввод, например:
# echo "Миша
# 12" | python3 example.py

# ПЛАН РЕШЕНИЯ:
# 1. Спросить имя (это будет строка)
# 2. Спросить возраст и сразу превратить его в целое число
# 3. Посчитать возраст через 5 лет и напечатать результат

name = input("Как тебя зовут? ")        # шаг 1: name -- это str
age_text = input("Сколько тебе лет? ")   # то, что ввели -- пока тоже str
age = int(age_text)                       # шаг 2: превращаем текст в число

future_age = age + 5                      # шаг 3: считаем возраст через 5 лет

print("Привет,", name + "!")
print("Сейчас тебе", age, "лет.")
print("Через 5 лет тебе будет", future_age, "лет.")
