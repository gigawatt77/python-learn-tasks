# Проверить, может ли ребёнок пойти в поход. Для этого нужно:
# возраст не меньше 10 лет И разрешение от родителей есть.
# Отдельно проверить: можно ли взять с собой собаку, если собака
# дружелюбная ИЛИ на поводке.

# ПЛАН РЕШЕНИЯ:
# 1. Завести переменные: возраст, есть ли разрешение, дружелюбная ли собака,
#    на поводке ли собака
# 2. Проверить условие похода с помощью and
# 3. Проверить условие про собаку с помощью or

vozrast = 11
est_razreshenie = True
sobaka_druzhelyubnaya = False
sobaka_na_povodke = True

# and сработает, только если оба условия True
if vozrast >= 10 and est_razreshenie:
    print("Можно идти в поход!")
else:
    print("В этот раз в поход нельзя")

# or сработает, если хотя бы одно условие True
if sobaka_druzhelyubnaya or sobaka_na_povodke:
    print("Собаку можно взять с собой")
else:
    print("Собаку лучше оставить дома")

# not переворачивает значение — проверим, что собака НЕ агрессивная
sobaka_agressivnaya = False
if not sobaka_agressivnaya:
    print("Собака точно не опасна")
