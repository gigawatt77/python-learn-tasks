# Определить, пускать ли ребёнка на аттракцион в парке, если рост
# ребёнка (в сантиметрах) хранится в переменной. Если рост меньше 120 см —
# нельзя, если от 120 до 149 см — можно, но только со взрослым, если
# 150 см и больше — можно одному.

# ПЛАН РЕШЕНИЯ:
# 1. Завести переменную с ростом ребёнка
# 2. Проверить рост с помощью if/elif/else
# 3. Напечатать подходящее сообщение для каждого случая

rost = 135  # рост ребёнка в сантиметрах

if rost < 120:                                  # первая проверка: рост меньше 120
    print("Извини, этот аттракцион пока рано.")
elif rost < 150:                                # рост от 120 до 149 включительно
    print("Можно кататься, но только со взрослым!")
else:                                           # рост 150 см и больше
    print("Можно кататься одному!")

print("Рост ребёнка:", rost, "см")              # выводим рост для наглядности
