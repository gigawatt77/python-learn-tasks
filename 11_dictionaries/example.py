# ЗАДАЧА:
# Есть словарь с оценками ученика по предметам. Нужно напечатать оценку
# по конкретному предмету, добавить новый предмет с оценкой, удалить
# предмет, который больше не изучается, а затем вывести весь дневник
# и посчитать средний балл.

# ПЛАН РЕШЕНИЯ:
# 1. Создать словарь "предмет -> оценка"
# 2. Напечатать оценку по одному предмету (доступ по ключу)
# 3. Добавить новый предмет и удалить один старый
# 4. Перебрать словарь циклом for и посчитать средний балл

diary = {"Математика": 5, "Русский язык": 4, "Физкультура": 5, "Труд": 3}

print("Оценка по математике:", diary["Математика"])   # шаг 2: доступ по ключу

diary["Информатика"] = 5   # шаг 3: добавили новый предмет
del diary["Труд"]          # удалили предмет "Труд"

print("Дневник после изменений:")
total = 0
count = 0
for subject, grade in diary.items():   # шаг 4: перебор пар ключ-значение
    print(subject, "-", grade)
    total = total + grade
    count = count + 1

average = total / count
print(f"Средний балл: {average:.2f}")
